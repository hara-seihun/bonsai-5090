#!/usr/bin/env python3
"""Export a run's best exact configuration as a static production header.

tune/export.py RUN_DIR [--out tune/best.hpp]
The header carries body genes, segment classes, boundaries and the measured
per-class grids, so `src/schedule.cu` compiled with -DHALO_TUNE_CONFIG='"tune/best.hpp"'
reproduces the winner without the driver.
"""
import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import space  # noqa: E402

ap = argparse.ArgumentParser()
ap.add_argument("run")
ap.add_argument("--out", default=str(Path(__file__).resolve().parent / "best.hpp"))
a = ap.parse_args()
best = json.loads((Path(a.run) / "best.json").read_text())
c = space.Config.from_json(best["config"])
c.grids = {m: g for m, g in zip(c.class_list(), best["grid_vector"]) if g}
hdr = c.header(with_grids=True)
note = (f"// best exact configuration from {a.run}: {best['tok_s']:.2f} tok/s s1 on pod B "
        f"(reference row32 {best.get('ref_tok_s')}), batch {best['batch']}\n")
Path(a.out).write_text(hdr.replace("// generated by tune/space.py; do not edit\n", "// generated by tune/export.py; do not edit\n" + note))
Path(a.out).with_suffix(".json").write_text(json.dumps({"tok_s": best["tok_s"], "grid_vector": best["grid_vector"], "config": c.to_json(),
                                                         "describe": c.describe(), "guard": best.get("guard")}, indent=1))
print(a.out)
