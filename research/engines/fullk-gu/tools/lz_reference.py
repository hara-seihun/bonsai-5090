#!/usr/bin/env python3
"""NumPy port of the LZ penalty reference code (tginart/sglang lz_penalty.py @ab08e697,
compute_lz_penalty_stateless) used to generate bench/lz_penalty_vectors.h for `make lz-penalty-test`.

Usage: tools/lz_reference.py > bench/lz_penalty_vectors.h
"""
import math
import numpy as np


def reference(W, vocab, n):
    """Penalty (subtracted from logits, before alpha) for every vocabulary token, as the reference computes it."""
    W = np.asarray(W, dtype=np.int64)
    w = W.size
    if w <= n:
        return np.zeros(vocab)
    head = W[:-1]
    windows = np.lib.stride_tricks.sliding_window_view(head, n)   # (w - n, n), as unfold(0, n, 1)
    E = windows == W[-n:][None, :]
    U = np.cumprod(E[:, ::-1].astype(np.float64), axis=1).sum(axis=1).astype(np.int64)
    match_context = W[n:]
    G = np.arange(vocab)
    M = (G[:, None] == match_context[None, :]).astype(np.int64)
    K = M * U[None, :] + M
    N = K.shape[1]
    dist = np.arange(N - 1, -1, -1, dtype=np.float64) + 1
    mask = K > 0
    distances = np.where(mask, dist[None, :], np.inf)
    max_len = K.max(axis=1, keepdims=True)
    best = (K == max_len) & mask
    min_dist = np.where(best, distances, np.inf).min(axis=1)
    cost = np.where(np.isfinite(min_dist), np.log2(np.where(np.isfinite(min_dist), min_dist, 1.0)), np.inf)
    lv = math.log2(vocab)
    RP = np.clip(cost, 0.0, lv)
    return lv - RP


def main():
    rng = np.random.default_rng(20261009)
    cases = []
    vocab = 12
    for case in range(40):
        window = int(rng.choice([16, 24, 40]))
        buffer = int(rng.choice([2, 4, 8]))
        length = int(rng.integers(1, 70))
        if case % 3 == 0:   # periodic stretches, as in a loop
            period = int(rng.integers(1, 9))
            unit = rng.integers(0, vocab, period)
            seq = np.concatenate([rng.integers(0, vocab, length // 3), np.tile(unit, length)])[:length]
        else:
            seq = rng.integers(0, 5 if case % 2 else vocab, length)
        W = seq[-window:]
        pen = reference(W, vocab, buffer)
        cases.append((window, buffer, seq.tolist(), pen.tolist()))
    print("// Generated by tools/lz_reference.py (NumPy port of tginart/sglang lz_penalty.py @ab08e697). Do not edit.")
    print("#pragma once")
    print("namespace lzref {")
    print(f"constexpr int VOCAB = {vocab};")
    print("struct Case { int window, buffer, n; int seq[80]; double pen[VOCAB]; };")
    print("static const Case cases[] = {")
    for window, buffer, seq, pen in cases:
        print(f"  {{{window}, {buffer}, {len(seq)}, {{{', '.join(map(str, seq)) or '0'}}}, {{{', '.join(f'{p:.12g}' for p in pen)}}}}},")
    print("};")
    print("}  // namespace lzref")


if __name__ == "__main__":
    main()
